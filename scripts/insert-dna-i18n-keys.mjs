// ── Language block boundaries ──────────────────────────────────────────────────
// (start line numbers from grep, 1-indexed)
const LANG_STARTS = {
  en:      35,
  es:    1297,
  fr:    2356,
  de:    3415,
  pt:    4474,
  it:    5533,
  nl:    6592,
  pl:    7651,
  ru:    8710,
  ar:    9769,
  "zh-CN": 10828,
  "zh-TW": 11890,
  ja:   12950,
  ko:   14010,
  hi:   15071,
  sw:   16132,
};

const lines = src.split("\n");

// For each language, find its closing `  },` line (2-space indent) — the first
// one that appears AFTER the block's opening line.
const langKeys = Object.keys(LANG_STARTS);

// Build index: for each lang, find the first `  },` after its start line.
const insertions = []; // { lineIndex: number (0-based), text: string }

for (const lang of langKeys) {
  const startIdx = LANG_STARTS[lang] - 1; // convert to 0-based
  let closingIdx = -1;
  for (let i = startIdx + 1; i < lines.length; i++) {
    if (lines[i] === "  },") {
      closingIdx = i;
      break;
    }
  }
  if (closingIdx === -1) {
    console.error(`Could not find closing '  },' for language: ${lang}`);
    continue;
  }
  const snippet = KEYS[lang];
  if (!snippet) {
    console.error(`No keys defined for language: ${lang}`);
    continue;
  }
  insertions.push({ lineIndex: closingIdx, text: snippet });
}

// Sort insertions in REVERSE order so later insertions don't shift earlier ones.
insertions.sort((a, b) => b.lineIndex - a.lineIndex);

for (const { lineIndex, text } of insertions) {
  // Insert the new lines before the closing `  },`
  const newLines = text.split("\n");
  lines.splice(lineIndex, 0, ...newLines);
}

const result = lines.join("\n");
writeFileSync(FILE, result, "utf8");
console.log(`Done. Inserted keys into ${insertions.length} language blocks.`);
